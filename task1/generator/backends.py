"""Pluggable image-generation backends. Task 1's default stays `programmatic` (matplotlib — exact,
free, deterministic, gives real per-target bboxes) as the spec asks for; `diffusion` and `gan` are
added here as opt-in alternatives, selected by `SETTINGS.generation_backend` in config.py, for when
a diagram alone isn't enough and a photographic/illustrative background is wanted instead.

Both generative backends return an EMPTY bbox dict — a diffusion/GAN image has no code-level notion
of "where the nucleus is", so `expected_visual_region` can't be measured the way `bbox_of()` measures
a matplotlib patch. That's not a corner case to special-case away: it's exactly the Task 6 handoff —
run SAM on the generated image to get real target boxes, the same way a teacher-supplied photo would
be handled. See the module docstrings below for why GANs specifically aren't a good fit here.
"""
from __future__ import annotations

from typing import Protocol

from PIL import Image

from task1.config import SETTINGS
from task1.schemas import BBox, Question


class GenerationBackend(Protocol):
    def build(self, question: Question, width: int, height: int) -> tuple[Image.Image, dict[str, BBox]]:
        """-> (background image sized width x height, {target_label: BBox} — may be empty)."""
        ...


# --------------------------------------------------------------------------- 1. programmatic (default)
class ProgrammaticBackend:
    """matplotlib diagrams, exact pixel bboxes read back from the real rendered patches. See
    generator/diagrams.py. This is the only backend the spec actually requires; it's the default."""

    def build(self, question: Question, width: int, height: int) -> tuple[Image.Image, dict[str, BBox]]:
        import io

        import matplotlib.pyplot as plt

        from task1.generator.diagrams import BUILDERS, bbox_of

        builder = BUILDERS.get(question.type)
        if builder is None:
            raise ValueError(f"no diagram builder registered for question type '{question.type}'")

        dpi = 150
        fig, ax = plt.subplots(figsize=(width / dpi, height / dpi), dpi=dpi)
        patches = builder(ax, question)
        fig.canvas.draw()
        bboxes = {label: bbox_of(fig, patch) for label, patch in patches.items()}

        buf = io.BytesIO()
        fig.savefig(buf, format="png", dpi=dpi, facecolor="white")
        plt.close(fig)
        buf.seek(0)
        image = Image.open(buf).convert("RGB").resize((width, height))
        return image, bboxes


# --------------------------------------------------------------------------- 2. diffusion (optional)
class DiffusionBackend:
    """Local text-to-image diffusion via `diffusers`, for a photographic/illustrative background that
    a hand-drawn diagram can't give (e.g. "a real heart", not a labeled oval). Uses SD-Turbo by
    default: a ONE-STEP distilled Stable Diffusion that fits and runs fast on an 8GB GPU
    (`SETTINGS.device`, same auto-detection as the validators) — fp16 on CUDA, fp32 on CPU (slow but
    works). Swap `SETTINGS.diffusion_model` for `stabilityai/sdxl-turbo` for higher quality if VRAM
    allows (still fits in 8GB at fp16, just slower than SD-Turbo).

    The question/label TEXT is never generated by the diffusion model — the same PIL overlay step
    (generator/renderer.py) draws it afterward, because in-image text generation is the one thing
    these models are still unreliable at (see the Task 7 study). This backend only supplies the
    background picture.
    """

    _pipe = None

    def _get_pipeline(self):
        if DiffusionBackend._pipe is None:
            import torch
            from diffusers import AutoPipelineForText2Image

            from task1.device import resolve_device

            device = resolve_device()
            dtype = torch.float16 if device == "cuda" else torch.float32
            # `torch_dtype` alone only controls the in-memory dtype AFTER download; without
            # `variant="fp16"` diffusers still downloads the full fp32 checkpoint files (~5GB for
            # SD-Turbo) and casts them afterward. Ask for the smaller fp16 checkpoint FILES too when
            # on GPU, and fall back to the default (fp32) files if the repo has no fp16 variant.
            kwargs = {"torch_dtype": dtype}
            if dtype == torch.float16:
                kwargs["variant"] = "fp16"
            try:
                pipe = AutoPipelineForText2Image.from_pretrained(SETTINGS.diffusion_model, **kwargs)
            except Exception:                                           # noqa: BLE001 - no fp16 variant on the hub
                kwargs.pop("variant", None)
                pipe = AutoPipelineForText2Image.from_pretrained(SETTINGS.diffusion_model, **kwargs)
            DiffusionBackend._pipe = pipe.to(device)
        return DiffusionBackend._pipe

    def build(self, question: Question, width: int, height: int) -> tuple[Image.Image, dict[str, BBox]]:
        pipe = self._get_pipeline()
        # SD-Turbo has no CFG / negative-prompt training (guidance_scale=0.0), so every word here
        # competes for the same, single pass of attention — a prompt stuffed with negations
        # ("no text, no watermark...") dilutes the one thing that actually matters: WHAT to draw.
        # Keep it short and entirely positive.
        subject = question.background_prompt or f"{question.topic.replace('.', ' ')}"
        prompt = f"{subject}, clean medical textbook illustration, simple flat colors, plain white background"
        image = pipe(prompt=prompt, num_inference_steps=SETTINGS.diffusion_steps,
                    guidance_scale=SETTINGS.diffusion_guidance_scale,
                    height=max(512, height - height % 8), width=max(512, width - width % 8)).images[0]
        return image.convert("RGB").resize((width, height)), {}


# --------------------------------------------------------------------------- 3. GAN (optional, limited)
class GANBackend:
    """A pretrained unconditional GAN (DCGAN, via `facebookresearch/pytorch_GAN_zoo` through
    `torch.hub`), included because it was asked for, not because it's a good fit for this task.

    Two real limits, not implementation gaps:
      1. It is NOT prompt-controllable. An unconditional GAN samples from the distribution it was
         trained on (its hub default is faces) — it cannot be asked for "a cell" or "a heart" the way
         the diffusion backend can, because there is no text-conditioning path in the model.
      2. Current open, locally-runnable GANs with reliable TEXT-conditioned generation and legible
         in-image text are not a mature, actively-maintained option the way diffusion models are —
         this is exactly the gap the diffusion/text-to-image literature review in the Task 7 study
         already covers, and it hasn't changed for GANs specifically.

    So: wired up and runnable (genuinely useful for an abstract/textured backdrop, e.g. a decorative
    background behind a shape question), but `programmatic` or `diffusion` are the backends to use
    for anything that has to depict a specific topic.
    """

    _model = None

    def _get_model(self):
        if GANBackend._model is None:
            import torch

            from task1.device import resolve_device

            model = torch.hub.load("facebookresearch/pytorch_GAN_zoo:hub", SETTINGS.gan_hub_model,
                                   pretrained=True, useGPU=resolve_device() == "cuda")
            GANBackend._model = model
        return GANBackend._model

    def build(self, question: Question, width: int, height: int) -> tuple[Image.Image, dict[str, BBox]]:
        import numpy as np

        model = self._get_model()
        noise, _ = model.buildNoiseData(1)
        with __import__("torch").no_grad():
            generated = model.test(noise)
        array = ((generated[0].permute(1, 2, 0).cpu().numpy() + 1) / 2 * 255).clip(0, 255).astype(np.uint8)
        return Image.fromarray(array).convert("RGB").resize((width, height)), {}


BACKENDS: dict[str, "GenerationBackend"] = {
    "programmatic": ProgrammaticBackend(),
    "diffusion": DiffusionBackend(),
    "gan": GANBackend(),
}


def get_backend(name: str | None = None) -> "GenerationBackend":
    name = name or SETTINGS.generation_backend
    backend = BACKENDS.get(name)
    if backend is None:
        raise ValueError(f"unknown generation_backend '{name}'; choose one of {list(BACKENDS)}")
    return backend
